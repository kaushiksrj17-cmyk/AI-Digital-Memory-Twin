"""Voice Domain Models, Schemas, and State Representations for ECHO.

Research Title: Evidence-Grounded, Privacy-Preserving Multimodal AI for
                Interactive Digital Memory Preservation.

Three distinct audio categories:
1. ORIGINAL_RECORDING — authentic audio uploaded or preserved by an authorized user.
2. TRANSCRIPTION — text extracted from an audio recording or live voice input.
3. AI_GENERATED_MEMORIAL_VOICE — synthesized speech generated by the application.

CRITICAL ETHICAL REQUIREMENTS:
- Never present synthesized audio as an original recording.
- Never claim the generated voice is the actual person, their consciousness, or authentic current speech.
- Label every synthesized response:
  "AI-GENERATED MEMORIAL VOICE — SYNTHETIC AUDIO, NOT AN ORIGINAL RECORDING."
- If custom voice synthesis is unavailable, label playback as a generic AI-generated voice.
"""

from pydantic import BaseModel, Field, ConfigDict
from typing import Optional, List, Dict, Any
from datetime import datetime, timezone
from uuid import uuid4

from models.enums import (
    VoiceProfileStatus,
    VoiceType,
    VoiceProcessingState,
    AudioCategory,
    ConsentStatus,
    ConsentType,
    ConfidenceLevel,
    GuardianDecision,
)
from models.conversation import RAGQueryResponse, ResponseSource

MANDATORY_MEMORIAL_DISCLOSURE = "AI-GENERATED MEMORIAL VOICE — SYNTHETIC AUDIO, NOT AN ORIGINAL RECORDING."
GENERIC_VOICE_DISCLOSURE = "GENERIC AI-GENERATED SYNTHETIC VOICE — NOT THE MEMORIAL PERSON'S VOICE."


# ==============================================================================
# Voice Profile Models
# ==============================================================================

class VoiceProfileBase(BaseModel):
    name: str = Field(..., description="Display label for the voice profile")
    description: Optional[str] = Field(None, description="Description or archival provenance notes")
    voice_type: VoiceType = Field(
        default=VoiceType.GENERIC_SYNTHETIC,
        description="Voice type: generic synthetic or authorized memorial custom"
    )
    supported_languages: List[str] = Field(
        default=["en", "ta", "hi"],
        description="Supported ISO language codes: English, Tamil, Hindi"
    )
    provider_id: str = Field(
        default="mock-tts",
        description="Identifier of configured speech synthesis provider"
    )
    provider_voice_id: Optional[str] = Field(
        default="echo-system-voice-en-01",
        description="Provider-internal voice identifier"
    )
    retention_policy: str = Field(
        default="STANDARD_ARCHIVE",
        description="Retention policy for reference samples and generated assets"
    )
    sample_duration_seconds: Optional[float] = Field(
        default=0.0,
        description="Total duration of authorized voice training/reference samples"
    )
    metadata_json: Dict[str, Any] = Field(
        default_factory=dict,
        description="Minimal operational metadata for auditing"
    )


class VoiceProfileCreate(VoiceProfileBase):
    memorial_profile_id: str = Field(default="default-profile-001")
    owner_id: str = Field(default="demo-user-001")
    consent_id: Optional[str] = Field(None, description="Associated verified consent record ID")


class VoiceProfileUpdate(BaseModel):
    name: Optional[str] = None
    description: Optional[str] = None
    provider_voice_id: Optional[str] = None
    retention_policy: Optional[str] = None
    metadata_json: Optional[Dict[str, Any]] = None


class VoiceProfile(VoiceProfileBase):
    id: str = Field(default_factory=lambda: str(uuid4()))
    memorial_profile_id: str = Field(default="default-profile-001")
    owner_id: str = Field(default="demo-user-001")
    status: VoiceProfileStatus = Field(default=VoiceProfileStatus.PENDING_CONSENT)
    consent_id: Optional[str] = None
    consent_status: ConsentStatus = Field(default=ConsentStatus.PENDING)
    consent_verified_at: Optional[datetime] = None
    revoked_at: Optional[datetime] = None
    disabled_at: Optional[datetime] = None
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    model_config = ConfigDict(from_attributes=True)


# ==============================================================================
# Voice Session & State Machine Models
# ==============================================================================

class VoiceSessionBase(BaseModel):
    memorial_profile_id: str = Field(default="default-profile-001")
    user_id: str = Field(default="demo-user-001")
    language: str = Field(default="en", description="Target interaction language: en, ta, hi")
    voice_profile_id: Optional[str] = None
    conversation_session_id: Optional[str] = None


class VoiceSessionCreate(VoiceSessionBase):
    pass


class VoiceSession(VoiceSessionBase):
    id: str = Field(default_factory=lambda: str(uuid4()))
    state: VoiceProcessingState = Field(default=VoiceProcessingState.IDLE)
    voice_type: VoiceType = Field(default=VoiceType.GENERIC_SYNTHETIC)
    
    # Transcript lifecycle
    original_transcript: Optional[str] = None
    edited_transcript: Optional[str] = None
    is_transcript_edited: bool = False
    
    # Audio references
    input_audio_id: Optional[str] = None
    response_audio_id: Optional[str] = None
    
    # Evidence & Guardian outcomes
    last_rag_response: Optional[RAGQueryResponse] = None
    last_guardian_status: Optional[GuardianDecision] = None
    
    # Operational telemetry
    error_message: Optional[str] = None
    latency_metrics: Dict[str, float] = Field(default_factory=dict)
    
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    model_config = ConfigDict(from_attributes=True)


# ==============================================================================
# Speech-to-Text & Audio Upload Payloads
# ==============================================================================

class AudioUploadResponse(BaseModel):
    audio_id: str
    audio_category: AudioCategory = AudioCategory.ORIGINAL_RECORDING
    filename: str
    mime_type: str
    file_size_bytes: int
    duration_seconds: Optional[float] = None
    sha256_checksum: str
    message: str = "Audio uploaded and validated safely."
    is_mock: bool = False


class TranscriptionResponse(BaseModel):
    transcript_id: str = Field(default_factory=lambda: str(uuid4()))
    audio_id: Optional[str] = None
    audio_category: AudioCategory = AudioCategory.TRANSCRIPTION
    text: str
    language: str = "en"
    duration_seconds: float = 0.0
    confidence_score: float = 1.0
    segments: List[Dict[str, Any]] = Field(default_factory=list)
    is_mock: bool = False
    provider_name: str = "MockSTTProvider"
    message: str = "Transcription completed."


# ==============================================================================
# Text-to-Speech & Playback Payloads
# ==============================================================================

class VoiceSynthesisRequest(BaseModel):
    text: str = Field(..., description="Approved response text that passed Phase 5 Memory Guardian")
    voice_profile_id: Optional[str] = None
    language: Optional[str] = "en"
    speed: Optional[float] = Field(default=1.0, ge=0.5, le=2.0)
    volume: Optional[float] = Field(default=1.0, ge=0.1, le=1.5)
    pitch: Optional[float] = Field(default=1.0, ge=0.5, le=1.5)
    session_id: Optional[str] = None
    user_id: Optional[str] = "demo-user-001"
    memorial_profile_id: Optional[str] = "default-profile-001"


class VoiceSynthesisResponse(BaseModel):
    audio_id: str
    audio_url: str = Field(..., description="Authenticated playback URL (/api/v1/voice/audio/{audio_id})")
    audio_category: AudioCategory = AudioCategory.AI_GENERATED_MEMORIAL_VOICE
    voice_type: VoiceType = VoiceType.GENERIC_SYNTHETIC
    format: str = "audio/wav"
    duration_seconds: float
    file_size_bytes: int
    is_mock: bool = False
    is_watermarked: bool = True
    watermark_label: str = "[ECHO-AI-MEMORIAL-VOICE-VERIFIED]"
    ethical_disclosure: str = MANDATORY_MEMORIAL_DISCLOSURE
    voice_disclosure: str = MANDATORY_MEMORIAL_DISCLOSURE
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


# ==============================================================================
# Complete Pipeline Request & Response
# ==============================================================================

class VoiceInteractionResponse(BaseModel):
    session_id: str
    state: VoiceProcessingState
    transcript: str
    is_transcript_edited: bool = False
    rag_response: RAGQueryResponse
    synthesis: Optional[VoiceSynthesisResponse] = None
    synthesis_blocked: bool = False
    synthesis_blocked_reason: Optional[str] = None
    audio_category: AudioCategory = AudioCategory.AI_GENERATED_MEMORIAL_VOICE
    ethical_disclosure: str = MANDATORY_MEMORIAL_DISCLOSURE
    total_latency_ms: float = 0.0
    latency_breakdown: Dict[str, float] = Field(default_factory=dict)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class VoiceTranscriptQueryRequest(BaseModel):
    session_id: str
    transcript_text: str
    is_edited: bool = False
    voice_profile_id: Optional[str] = None
    language: Optional[str] = "en"
    synthesize_audio: bool = True


